// Package object defines object instances, their observed status, and the
// file-based store that keeps them.
package object

import (
	"fmt"
	"regexp"
	"strings"
	"time"

	"gopkg.in/yaml.v3"
)

var (
	kindPart = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9]*$`)
	namePart = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]*$`)
)

// Ref identifies an object as "Kind/name".
type Ref struct {
	Kind string
	Name string
}

// ParseRef parses "Kind/name".
func ParseRef(s string) (Ref, error) {
	kind, name, ok := strings.Cut(s, "/")
	if !ok || !kindPart.MatchString(kind) || !namePart.MatchString(name) {
		return Ref{}, fmt.Errorf("invalid object reference %q, expected Kind/name", s)
	}
	return Ref{Kind: kind, Name: name}, nil
}

func (r Ref) String() string { return r.Kind + "/" + r.Name }

// MarshalYAML writes the reference as a plain string.
func (r Ref) MarshalYAML() (any, error) { return r.String(), nil }

// UnmarshalYAML reads a reference from a plain string.
func (r *Ref) UnmarshalYAML(node *yaml.Node) error {
	var s string
	if err := node.Decode(&s); err != nil {
		return err
	}
	parsed, err := ParseRef(s)
	if err != nil {
		return fmt.Errorf("line %d: %w", node.Line, err)
	}
	*r = parsed
	return nil
}

// Object is the declared part of an object: what the user has chosen.
type Object struct {
	Ref  Ref               `yaml:"object"`
	Uses map[string]Ref    `yaml:"uses,omitempty"`
	Set  map[string]string `yaml:"set,omitempty"`
}

// Resolved is a field value together with where it came from.
type Resolved struct {
	Value string `yaml:"value" json:"value"`
	From  string `yaml:"from" json:"from"`
}

// Verification records the outcome of the last verify run.
type Verification struct {
	OK bool      `yaml:"ok"`
	At time.Time `yaml:"at"`
}

// Status is the observed part of an object. It is generated by tbx and can
// always be rebuilt.
type Status struct {
	Ref        Ref                 `yaml:"object"`
	Resolved   map[string]Resolved `yaml:"resolved,omitempty"`
	Outputs    map[string]string   `yaml:"outputs,omitempty"`
	LastVerify *Verification       `yaml:"lastVerify,omitempty"`
	// AppliedAt is when the object was last brought into the desired state.
	AppliedAt *time.Time `yaml:"appliedAt,omitempty"`
}

// Values returns the resolved fields overlaid with the outputs, which is what
// other objects can reference.
func (s *Status) Values() map[string]string {
	values := make(map[string]string, len(s.Resolved)+len(s.Outputs))
	for name, r := range s.Resolved {
		values[name] = r.Value
	}
	for name, v := range s.Outputs {
		values[name] = v
	}
	return values
}
